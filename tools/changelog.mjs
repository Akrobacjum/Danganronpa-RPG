/**
 * CHANGELOG.md, built from the release notes (E59 C5, 13.11.2026; D47's "a CHANGELOG built from the notes").
 * ---------------------------------------------------------------------------
 *     node tools/changelog.mjs           the text it would write, to stdout
 *     node tools/changelog.mjs --write   CHANGELOG.md written from .github/release-notes
 *
 * An index, not a copy: one line per release, newest first, its title and a link to its notes file. The notes are
 * 94 files and 1.4 MB on 421f2395 (one of them 70 000 characters), and they stay the one place a release is
 * described; a CHANGELOG holding their text would be a second copy to keep. A title is the notes' first "# " heading
 * with its "<version> - " taken off, or, for the older notes that open with a sentence instead (1.2.0 and 1.2.15 to
 * 1.2.27; there are no 1.2.28 or 1.2.29 notes), that sentence with its bold marks taken off. No date: the notes carry none, and a tag's date is not in a
 * shallow checkout, so the text depends on the notes files alone and the check below reads the same on any clone.
 *
 * `node tools/check.mjs notes` holds CHANGELOG.md to `build()`: a notes file added without the CHANGELOG written
 * again is red, and the message says to run `--write`. Bare Node, no imports beyond node:*. CHANGELOG.md is
 * export-ignored: it is the repository's, and module.zip carries no notes.
 */
import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const NOTES = path.join(".github", "release-notes");
const NAME = /^v(\d+)\.(\d+)\.(\d+)\.md$/;

/** The title of one notes file's text, for version `v` ("1.2.109"). */
export function titleOf(text, v) {
    const first = String(text).replace(/\r\n/g, "\n").split("\n").find(l => l.trim()) ?? "";
    if (first.startsWith("# ")) {
        const heading = first.slice(2).trim();
        const prefix = `${v} - `;
        return heading.startsWith(prefix) ? heading.slice(prefix.length).trim() : heading;
    }
    const plain = first.replace(/\*\*/g, "").trim();
    const sentence = /^(.+?[.!?])(\s|$)/.exec(plain)?.[1] ?? plain;
    return sentence;
}

/** The CHANGELOG's text from `{ "v1.2.0.md": text, ... }`; files not named vX.Y.Z.md are left out. */
export function build(files) {
    const rows = Object.entries(files)
        .map(([name, text]) => [NAME.exec(name), name, text])
        .filter(([m]) => m)
        .map(([m, name, text]) => ({ n: m.slice(1).map(Number), v: m.slice(1).join("."), name, title: titleOf(text, m.slice(1).join(".")) }))
        .sort((a, b) => b.n[0] - a.n[0] || b.n[1] - a.n[1] || b.n[2] - a.n[2]);
    const lines = [
        "# Changelog",
        "",
        "Every release of Danganronpa RPG, newest first, with a link to its notes. Generated by `node tools/changelog.mjs",
        "--write` from `.github/release-notes/`; do not edit by hand (`node tools/check.mjs notes` holds it to that folder).",
        ""
    ];
    for (const row of rows) lines.push(`- **${row.v}** - ${row.title} ([notes](.github/release-notes/${row.name}))`);
    return lines.join("\n") + "\n";
}

/** The notes files of a checkout at `root`, as `build` takes them. */
export function readNotes(root) {
    const dir = path.join(root, NOTES);
    return Object.fromEntries(fs.readdirSync(dir).filter(f => NAME.test(f)).map(f => [f, fs.readFileSync(path.join(dir, f), "utf8")]));
}

if (process.argv[1] && path.resolve(process.argv[1]) === url.fileURLToPath(import.meta.url)) {
    const root = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), "..");
    const text = build(readNotes(root));
    if (process.argv.includes("--write")) {
        fs.writeFileSync(path.join(root, "CHANGELOG.md"), text);
        console.log(`changelog: CHANGELOG.md written, ${text.split("\n").filter(l => l.startsWith("- ")).length} release(s)`);
    } else {
        process.stdout.write(text);
    }
}
