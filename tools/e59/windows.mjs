#!/usr/bin/env node
/**
 * The window census (E59 C2, 14.11.2026): every window the module opens, by name, with what each of R6750-R6756 read of
 * it, written into docs/dev/e59/WINDOWS.md. The same readers the suite runs (scripts/tests-windows.mjs), on the files at
 * the root of this checkout: scripts/ less the suite's own files, and module.json's sheets.
 *
 *   node tools/e59/windows.mjs           print the census
 *   node tools/e59/windows.mjs --write   write docs/dev/e59/WINDOWS.md
 *   node tools/e59/windows.mjs --check   exit 1 when the file is not what --write would write
 *
 * The suite reads the files Foundry serves, reached from module.mjs by their imports; this tool reads every .mjs of
 * scripts/. At 123f8242 both read the same 162 windows (the tool's count here, R6750's in the harness).
 */
import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const REPO = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), "..", "..");
const W = await import(url.pathToFileURL(path.join(REPO, "scripts", "tests-windows.mjs")).href);
const OUT = path.join(REPO, "docs", "dev", "e59", "WINDOWS.md");
const lf = t => t.replace(/\r\n?/g, "\n");

const dir = path.join(REPO, "scripts");
const sources = fs.readdirSync(dir).filter(f => f.endsWith(".mjs") && !/^tests(-[\w-]+)?\.mjs$/.test(f)).sort()
    .map(f => [f, lf(fs.readFileSync(path.join(dir, f), "utf8"))]);
const manifest = JSON.parse(fs.readFileSync(path.join(REPO, "module.json"), "utf8"));
const sheets = (manifest.styles ?? []).map(f => [f, lf(fs.readFileSync(path.join(REPO, f), "utf8"))]);

const sites = W.windowSites(sources);
const names = W.windowNames(sites);
const root = W.rootRule(sites), de = W.destructiveRule(sources, sites), tab = W.tabRule(sources, sites), foot = W.footerRule(sources, sites);
const floor = W.floorRule(sheets), gold = W.goldRule(sheets, sources), red = W.redRule(sheets);

const row = label => {
    const own = sites.filter(s => s.label === label);
    const kinds = [...new Set(own.map(s => s.kind))].join(", ");
    const lines = own.map(s => s.line).join(", ");
    return `| \`${label}\` | ${lines} | ${kinds} | ${foot.shapes.get(label) ?? "-"} | ${tab.read.includes(label) ? "yes" : ""} | ${de.read.includes(label) ? "yes" : ""} |`;
};
const list = (items, none = "none") => (items.length ? items.map(x => `- ${x}`).join("\n") : `- ${none}`);

const text = `# Every window, as read (E59 C2)

Generated by \`node tools/e59/windows.mjs --write\` from scripts/tests-windows.mjs, the readers R6750-R6756 run in
tier 0. Do not edit by hand: \`--check\` says when it is stale. It reads source and the served sheets, not a drawn
window (LIVE-E59-01 is the drawn one).

## The count

- ${names.length} windows in ${sites.length} sites, in ${new Set(sites.map(s => s.file)).size} files of scripts/ (a site is a \`drpgWindow\`,
  \`drpgConfirm\` or \`drpgPrompt\` call, a \`DrpgApp()\` class, or a Foundry window opened outside the kit; a window is its file and
  the top-level function or class it is opened in).
- By kind: ${Object.entries(sites.reduce((a, s) => ({ ...a, [s.kind]: (a[s.kind] ?? 0) + 1 }), {})).map(([k, n]) => `${k} ${n}`).join(", ")}.
- Footers by shape: ${Object.entries([...foot.shapes.values()].reduce((a, v) => ({ ...a, [v]: (a[v] ?? 0) + 1 }), {})).map(([k, n]) => `${k} ${n}`).join(", ")}.

## What each rule found

| Rule | Test | Read | Found | Kept, with a reason |
| --- | --- | ---: | ---: | --- |
| no window without \`.drpg-ui\` | R6750 | ${root.read.length} windows | ${root.found.length} | ${W.ROOT_OUTSIDE.map(o => `\`${o.label}\``).join(", ")} |
| \`drpg-destructive\` never the default, autofocus or under Enter | R6751 | ${de.read.length} windows with a destructive button, ${de.holders.length} footer builders, ${de.footers} footers with a default | ${de.found.length} | ${de.unread} default read only at run time (the kit throws) |
| one tab system | R6752 | ${tab.read.length} windows with the kit's tabs (${tab.users.length} places) | ${tab.found.length} | - |
| the footer contract | R6753 | ${foot.read.length} windows | ${foot.found.length} | ${foot.held.length} (FOOTER_KNOWN) |
| the 11 px floor | R6754 | ${floor.read.length} sizes (${floor.unread} not readable in Node) | ${floor.found.length} | ${floor.kept.length} outside windows (FLOOR_OUTSIDE) |
| gold only for Hope | R6755 | ${gold.reads} reads in ${gold.read.length} rules, ${gold.scripts} in scripts/ | ${gold.found.length} | ${W.GOLD_READERS.length} (GOLD_READERS) |
| red only on the GM's road | R6756 | ${red.read.length} button rules in a window's scope | ${red.found.length} | ${red.held.length} (RED_KEPT) |

### Found
${list([...root.found, ...de.found, ...tab.found, ...foot.found, ...floor.found, ...gold.found, ...red.found])}

### Kept: the footer (FOOTER_KNOWN)
${list(foot.held)}

### Kept: sizes under 11 px outside windows (FLOOR_OUTSIDE)
${list(floor.kept)}

### Kept: red on a window's button (RED_KEPT)
${list(red.held)}

## Every window

| Window | Line(s) | Kind | Footer | Tabs | Destructive |
| --- | --- | --- | --- | --- | --- |
${names.map(row).join("\n")}
`;

const mode = process.argv[2];
if (mode === "--write") {
    fs.writeFileSync(OUT, text);
    console.log(`windows: ${names.length} windows in ${sites.length} sites written to ${path.relative(REPO, OUT)}`);
} else if (mode === "--check") {
    const now = fs.existsSync(OUT) ? lf(fs.readFileSync(OUT, "utf8")) : "";
    if (now !== text) { console.log(`windows: ${path.relative(REPO, OUT)} is stale - run node tools/e59/windows.mjs --write`); process.exit(1); }
    console.log(`windows: ${path.relative(REPO, OUT)} holds the census (${names.length} windows)`);
} else process.stdout.write(text);
